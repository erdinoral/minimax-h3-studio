  function readLang() {
    try {
      const s = localStorage.getItem("h3-lang");
      if (s === "en" || s === "tr") return s;
    } catch {
      /* ignore */
    }
    return "en";
  }

  let lang = readLang();

  function t(key) {
    const pack = I18N[lang] || I18N.tr;
    if (pack[key] != null) return pack[key];
    return key;
  }

  function applyBound() {
    for (const row of BIND) {
      const sel = row[0];
      const key = row[1];
      const attr = row[2] || "text";
      const val = t(key);
      document.querySelectorAll(sel).forEach((el) => {
        if (attr === "placeholder") el.setAttribute("placeholder", val);
        else if (attr === "title") el.setAttribute("title", val);
        else if (attr === "html") el.innerHTML = val;
        else {
          el.textContent = val;
          if (el.dataset && el.dataset.chip != null) el.dataset.chip = val;
        }
      });
    }
    document.querySelectorAll("[data-purpose]").forEach((el) => {
      const k = el.dataset.purpose;
      if (!k) return;
      const val = t("purpose." + k);
      if (el.closest("#bible-genre")) return;
      el.textContent = val;
      if (el.dataset.chip != null) el.dataset.chip = val;
    });
    document.querySelectorAll("[data-style]").forEach((el) => {
      const k = el.dataset.style;
      if (!k) return;
      if (el.tagName === "OPTION") return;
      const val = t("style." + k);
      el.textContent = val;
      if (el.dataset.chip != null) el.dataset.chip = val + (lang === "tr" ? " tarz" : " look");
    });
    document.querySelectorAll("#dur-chips .chip, #dur-chips-cont .chip, #director-chips [data-clip], #cinema-duration option").forEach((el) => {
      const d = el.dataset.dur || el.dataset.clip || el.value;
      if (!d) return;
      if (el.tagName === "OPTION") {
        el.textContent = `${d} ${t("sec")}`;
        return;
      }
      el.textContent = `${d} ${t("sec")}`;
      if (el.dataset.chip != null) el.dataset.chip = `${d} ${t("sec")}`;
    });
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
    const bibleGenre = document.getElementById("bible-genre");
    if (bibleGenre) {
      [...bibleGenre.options].forEach((opt) => {
        opt.textContent = t("purpose." + opt.value);
      });
    }
    const bibleStyle = document.getElementById("bible-style");
    if (bibleStyle) {
      [...bibleStyle.options].forEach((opt) => {
        opt.textContent = t("style." + opt.value);
      });
    }
    document.querySelectorAll("#llm-provider option, #llm-provider-settings option").forEach((opt) => {
      const k = "llm.opt." + opt.value;
      const val = t(k);
      if (val !== k) opt.textContent = val;
    });
    document.querySelectorAll("#notify-provider option").forEach((opt) => {
      if (opt.value === "telegram") opt.textContent = t("notify.telegram");
      if (opt.value === "ntfy") opt.textContent = t("notify.ntfy");
    });
    document.querySelectorAll(".file-pick-btn[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll(".file-pick-name[data-i18n-empty]").forEach((el) => {
      const input = el.closest(".file-pick")?.querySelector(".file-pick-input");
      if (input && input.files && input.files.length) return;
      el.textContent = t(el.getAttribute("data-i18n-empty"));
    });
    const noneOpt = document.querySelector("#continue-source option[value='']");
    if (noneOpt) noneOpt.textContent = t("cont.pick");
    document.querySelectorAll("#scene-purpose-chips [data-purpose=music_video], #director-chips [data-purpose=music_video]").forEach((el) => {
      el.title = t("purpose.mvTitle");
    });
  }

  function syncLangSwitch() {
    document.querySelectorAll("#lang-switch [data-lang]").forEach((b) => {
      b.classList.toggle("on", b.dataset.lang === lang);
    });
    document.documentElement.lang = lang;
  }

  function applyI18n() {
    applyBound();
    syncLangSwitch();
    document.dispatchEvent(new CustomEvent("h3-lang", { detail: { lang } }));
  }

  function setLang(next) {
    lang = next === "en" ? "en" : "tr";
    try {
      localStorage.setItem("h3-lang", lang);
    } catch {
      /* ignore */
    }
    applyI18n();
  }

  window.H3_I18N = I18N;
  window.h3Lang = () => lang;
  window.t = t;
  window.applyI18n = applyI18n;
  window.setH3Lang = setLang;
  document.addEventListener("DOMContentLoaded", () => {
    document.getElementById("lang-switch")?.addEventListener("click", (e) => {
      const b = e.target.closest("[data-lang]");
      if (b) setLang(b.dataset.lang);
    });
    applyI18n();
  });
